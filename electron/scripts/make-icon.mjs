
import { deflateSync } from 'node:zlib'
import { writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const SIZE = 64
const px = new Uint8Array(SIZE * SIZE * 4)

const inside = (x, y) => {
  const r = 14
  const cx = Math.min(Math.max(x, r), SIZE - r)
  const cy = Math.min(Math.max(y, r), SIZE - r)
  return (x - cx) ** 2 + (y - cy) ** 2 <= r * r
}
const distToSegment = (px_, py_, ax, ay, bx, by) => {
  const dx = bx - ax
  const dy = by - ay
  const t = Math.max(0, Math.min(1, ((px_ - ax) * dx + (py_ - ay) * dy) / (dx * dx + dy * dy)))
  return Math.hypot(px_ - (ax + t * dx), py_ - (ay + t * dy))
}

for (let y = 0; y < SIZE; y++) {
  for (let x = 0; x < SIZE; x++) {
    const i = (y * SIZE + x) * 4
    // rounded square in the app accent colour
    const bg = inside(x + 0.5, y + 0.5)
    // a "V" glyph: two thick strokes meeting at the bottom
    const vDepth = Math.min(
      distToSegment(x, y, 16, 18, 32, 46),
      distToSegment(x, y, 48, 18, 32, 46)
    )
    const glyph = vDepth <= 5.5
    if (glyph) {
      px[i] = 255; px[i + 1] = 255; px[i + 2] = 255; px[i + 3] = 255
    } else if (bg) {
      px[i] = 61; px[i + 1] = 90; px[i + 2] = 254; px[i + 3] = 255
    }
  }
}

// --- minimal PNG encoder (RGBA, filter 0) ---
const crcTable = new Uint32Array(256)
for (let n = 0; n < 256; n++) {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  crcTable[n] = c >>> 0
}
const crc32 = (buf) => {
  let c = 0xffffffff
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
const chunk = (type, data) => {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([len, body, crc])
}
const ihdr = Buffer.alloc(13)
ihdr.writeUInt32BE(SIZE, 0)
ihdr.writeUInt32BE(SIZE, 4)
ihdr[8] = 8   // bit depth
ihdr[9] = 6   // colour type RGBA
const raw = Buffer.alloc(SIZE * (SIZE * 4 + 1))
for (let y = 0; y < SIZE; y++) {
  raw[y * (SIZE * 4 + 1)] = 0
  Buffer.from(px.buffer, y * SIZE * 4, SIZE * 4).copy(raw, y * (SIZE * 4 + 1) + 1)
}
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', ihdr),
  chunk('IDAT', deflateSync(raw, { level: 9 })),
  chunk('IEND', Buffer.alloc(0))
])

const here = dirname(fileURLToPath(import.meta.url))
const resources = join(here, '..', 'resources')
mkdirSync(resources, { recursive: true })
writeFileSync(join(resources, 'icon.png'), png)
const ts = '// Generated by scripts/make-icon.mjs — do not edit by hand.\n' +
  'export const trayIconDataUrl =\n  ' + JSON.stringify('data:image/png;base64,' + png.toString('base64')) + '\n'
writeFileSync(join(here, '..', 'src', 'main', 'icon.ts'), ts)
console.log('icon.png bytes:', png.length)
